-- Watchers, timers, and menubar items held only by locals can be garbage
-- collected once init.lua finishes, which silently stops them. Keep them here.
keepAlive = {}

local function notify(message, seconds)
  hs.alert.show(message, seconds or 1.2)
end

local function bind(mods, key, description, fn)
  table.insert(hotkeyDocs, {
    combo = table.concat(mods, "+") .. "+" .. key,
    description = description,
  })
  hs.hotkey.bind(mods, key, fn)
end

local function showCheatsheet()
  table.sort(hotkeyDocs, function(a, b)
    return a.combo < b.combo
  end)

  local lines = { "Hammerspoon shortcuts" }
  for _, item in ipairs(hotkeyDocs) do
    table.insert(lines, string.format("%s  -  %s", item.combo, item.description))
  end
  hs.alert.show(table.concat(lines, "\n"), 4)
end

local function reloadConfig(files)
  for _, file in ipairs(files) do
    if file:sub(-4) == ".lua" then
      hs.reload()
      return
    end
  end
end

keepAlive.reloader = hs.pathwatcher.new(hs.configdir, reloadConfig):start()

local home = os.getenv("HOME")
local appDirs = {
  "/Applications",
  "/Applications/Utilities",
  "/System/Applications",
  "/System/Applications/Utilities",
  "/System/Library/CoreServices/Finder.app",
  home .. "/Applications",
}

local function collectApps(path, seen, apps)
  if path:sub(-4) == ".app" then
    local name = path:match("([^/]+)%.app$")
    if not seen[name] then
      seen[name] = true
      table.insert(apps, { text = name, subText = path, path = path })
    end
    return
  end

  if hs.fs.attributes(path, "mode") ~= "directory" then
    return
  end
  for entry in hs.fs.dir(path) do
    if entry:sub(-4) == ".app" then
      collectApps(path .. "/" .. entry, seen, apps)
    end
  end
end

-- Scans on every open so newly installed apps appear without a reload.
local function installedApps()
  local seen, apps = {}, {}
  for _, dir in ipairs(appDirs) do
    collectApps(dir, seen, apps)
  end
  table.sort(apps, function(a, b)
    return a.text:lower() < b.text:lower()
  end)
  for _, app in ipairs(apps) do
    app.image = hs.image.iconForFile(app.path)
  end
  return apps
end

